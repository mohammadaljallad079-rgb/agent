"""Device identity.

A user may run the local runtime on several machines (laptop, desktop, work
computer). Each enrolled runtime instance has a *device identity* so audit,
permissions and synchronization can be scoped per device, and so a lost device
can be revoked without touching the others.

Two rules are load-bearing:

* **Never use a raw hardware identifier as the public identity.** Machine ids,
  MAC addresses and serial numbers are stable across reinstalls and can be
  correlated across services, so they are neither stored nor emitted. The
  public ``device_id`` is a random, prefixed identifier.
* **Enrollment is explicit and revocable.** A device starts ``PENDING``; an
  operator activates it. Revocation is terminal and audited.

The registry is an ABC so a durable (Postgres) implementation can be dropped in
later without touching callers; the in-memory implementation is what the local
runtime and tests use.
"""

from __future__ import annotations

import asyncio
from abc import ABC, abstractmethod
from datetime import UTC, datetime

from pydantic import BaseModel, ConfigDict, Field

from ..core.enums import DeviceStatus, PlatformKind
from ..core.errors import NotFoundError
from ..core.ids import PREFIX_DEVICE, new_id


def _utcnow() -> datetime:
    return datetime.now(UTC)


class DeviceIdentity(BaseModel):
    """An enrolled runtime instance belonging to a user."""

    model_config = ConfigDict(frozen=True)

    id: str = Field(default_factory=lambda: new_id(PREFIX_DEVICE))
    tenant_id: str
    user_id: str
    #: Human-friendly label ("Work laptop"); user supplied, not a machine id.
    label: str
    platform: PlatformKind = PlatformKind.UNKNOWN
    status: DeviceStatus = DeviceStatus.PENDING
    #: Opaque, non-secret runtime instance fingerprint (a random value the
    #: runtime generates locally). NOT a hardware identifier.
    instance_fingerprint: str = ""
    enrolled_at: datetime = Field(default_factory=_utcnow)
    activated_at: datetime | None = None
    revoked_at: datetime | None = None

    @property
    def active(self) -> bool:
        return self.status is DeviceStatus.ACTIVE

    def activate(self) -> DeviceIdentity:
        return self.model_copy(update={"status": DeviceStatus.ACTIVE, "activated_at": _utcnow()})

    def suspend(self) -> DeviceIdentity:
        return self.model_copy(update={"status": DeviceStatus.SUSPENDED})

    def revoke(self) -> DeviceIdentity:
        return self.model_copy(update={"status": DeviceStatus.REVOKED, "revoked_at": _utcnow()})


class DeviceRegistry(ABC):
    """Persistence contract for device identities."""

    @abstractmethod
    async def enroll(self, device: DeviceIdentity) -> DeviceIdentity: ...

    @abstractmethod
    async def get(self, device_id: str, *, tenant_id: str) -> DeviceIdentity: ...

    @abstractmethod
    async def list_for_user(self, *, tenant_id: str, user_id: str) -> list[DeviceIdentity]: ...

    @abstractmethod
    async def update(self, device: DeviceIdentity) -> DeviceIdentity: ...


class InMemoryDeviceRegistry(DeviceRegistry):
    """Process-local device registry (local runtime/tests)."""

    def __init__(self) -> None:
        self._items: dict[str, DeviceIdentity] = {}
        self._lock = asyncio.Lock()

    async def enroll(self, device: DeviceIdentity) -> DeviceIdentity:
        async with self._lock:
            self._items[device.id] = device
        return device

    async def get(self, device_id: str, *, tenant_id: str) -> DeviceIdentity:
        async with self._lock:
            device = self._items.get(device_id)
        if device is None or device.tenant_id != tenant_id:
            # Do not reveal whether another tenant's device exists.
            raise NotFoundError("device not found", details={"device_id": device_id})
        return device

    async def list_for_user(self, *, tenant_id: str, user_id: str) -> list[DeviceIdentity]:
        async with self._lock:
            return [
                d for d in self._items.values() if d.tenant_id == tenant_id and d.user_id == user_id
            ]

    async def update(self, device: DeviceIdentity) -> DeviceIdentity:
        async with self._lock:
            self._items[device.id] = device
        return device


def enroll_device(
    *,
    tenant_id: str,
    user_id: str,
    label: str,
    platform: PlatformKind,
    instance_fingerprint: str,
) -> DeviceIdentity:
    """Create a new ``PENDING`` device identity.

    The ``instance_fingerprint`` must be a random value generated by the local
    runtime, never a hardware identifier.
    """
    return DeviceIdentity(
        tenant_id=tenant_id,
        user_id=user_id,
        label=label,
        platform=platform,
        instance_fingerprint=instance_fingerprint,
    )
